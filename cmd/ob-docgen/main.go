	var buf bytes.Buffer

	summary := "Every typed failure code Onebox can emit: the loader's validation codes and the lifecycle failure contract, each with its meaning and resolving command."

	fmt.Fprintln(&buf, "---")
	fmt.Fprintln(&buf, `title: Error codes`)
	fmt.Fprintf(&buf, "description: %s\n", jsonString(summary))
	fmt.Fprintf(&buf, "summary: %s\n", jsonString(summary))
	fmt.Fprintln(&buf, "status: shipped")
	fmt.Fprintln(&buf, "generated: true")
	fmt.Fprintln(&buf, "sidebar:\n  order: 300")
	fmt.Fprintln(&buf, "read_when:")
	fmt.Fprintln(&buf, `  - "A command failed and you have a code but not a cause"`)
