// renderCLIPage asks the built binary to describe itself. The root command is
// unexported in package main, so shelling out is what keeps the CLI reference
// generated rather than transcribed. With no binary available the page is
// skipped rather than written stale.
func renderCLIPage(obBin string) (string, error) {
	if obBin == "" {
		found, err := exec.LookPath("ob")
		if err != nil {
			fmt.Fprintln(os.Stderr, "ob-docgen: no ob binary found, skipping the CLI reference (build it with `just build`)")
			return "", nil
		}
		obBin = found
	}

	root, err := help(obBin)
	if err != nil {
		return "", err
	}

	var buf bytes.Buffer
	summary := "Every ob command, its help text and its flags, taken from the binary itself."

	fmt.Fprintln(&buf, "---")
	fmt.Fprintln(&buf, "title: CLI commands")
	fmt.Fprintf(&buf, "description: %s\n", jsonString(summary))
	fmt.Fprintf(&buf, "summary: %s\n", jsonString(summary))
	fmt.Fprintln(&buf, "status: shipped")
	fmt.Fprintln(&buf, "generated: true")
	fmt.Fprintln(&buf, "sidebar:\n  order: 200")
	fmt.Fprintln(&buf, "read_when:")
	fmt.Fprintln(&buf, `  - "Looking up what a command does, or which flags it takes"`)
	fmt.Fprintln(&buf, `  - "Deciding whether a command contacts the target or changes it"`)
	fmt.Fprintln(&buf, "---")
	fmt.Fprintln(&buf)
	fmt.Fprintln(&buf, generatedMarker)
	fmt.Fprintln(&buf)
	fmt.Fprintln(&buf, "Generated from the binary, so it cannot describe a flag the CLI does not have.")
	fmt.Fprintln(&buf, "`ob <command> --help` is the same text.")
	fmt.Fprintln(&buf)

	fmt.Fprintln(&buf, "## ob")
	fmt.Fprintln(&buf)
	fmt.Fprintln(&buf, "```")
	fmt.Fprintln(&buf, strings.TrimRight(root, "\n"))
	fmt.Fprintln(&buf, "```")
	fmt.Fprintln(&buf)

	for _, name := range subcommands(root) {
		body, err := help(obBin, strings.Fields(name)...)
		if err != nil {
			continue
		}
		fmt.Fprintf(&buf, "## ob %s\n\n", name)
		fmt.Fprintln(&buf, "```")
		fmt.Fprintln(&buf, strings.TrimRight(body, "\n"))
		fmt.Fprintln(&buf, "```")
		fmt.Fprintln(&buf)

		for _, nested := range subcommands(body) {
			full := name + " " + nested
			nestedBody, err := help(obBin, strings.Fields(full)...)
			if err != nil {
				continue
			}
			fmt.Fprintf(&buf, "### ob %s\n\n", full)
			fmt.Fprintln(&buf, "```")
			fmt.Fprintln(&buf, strings.TrimRight(nestedBody, "\n"))
			fmt.Fprintln(&buf, "```")
			fmt.Fprintln(&buf)
		}
	}

	return buf.String(), nil
}

func help(bin string, args ...string) (string, error) {
	cmd := exec.Command(bin, append(args, "--help")...)
	cmd.Env = append(os.Environ(), "NO_COLOR=1")
	var out, errOut bytes.Buffer
	cmd.Stdout = &out
	cmd.Stderr = &errOut
	if err := cmd.Run(); err != nil && out.Len() == 0 {
		return "", fmt.Errorf("ob %s --help: %w: %s", strings.Join(args, " "), err, strings.TrimSpace(errOut.String()))
	}
	return out.String(), nil
}

// subcommands reads the "Available Commands:" section cobra prints. Parsing
// help output is coarse, but it is the only view of the command tree available
// from outside package main, and a missing command is visible rather than
// silent.
func subcommands(helpText string) []string {
	var out []string
	inSection := false
	for _, line := range strings.Split(helpText, "\n") {
		trimmed := strings.TrimSpace(line)
		if strings.HasSuffix(trimmed, "Commands:") {
			inSection = true
			continue
		}
		if inSection {
			if trimmed == "" {
				inSection = false
				continue
			}
			if !strings.HasPrefix(line, " ") {
				inSection = false
				continue
			}
			name := strings.Fields(trimmed)
			if len(name) == 0 {
				continue
			}
			if name[0] == "help" || name[0] == "completion" {
				continue
			}
			out = append(out, name[0])
		}
	}
	sort.Strings(out)
	return out
}
