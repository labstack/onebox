func renderFieldPages(schema map[string]any) (map[string]string, error) {
	props, _ := schema["properties"].(map[string]any)
	if props == nil {
		return nil, fmt.Errorf("the JSON Schema has no top-level properties")
	}
	required := stringSet(schema["required"])

	// `blocks` is a template, not an accumulator. Aliasing it and appending
	// through the pointers made every field permanent process state, so a second
	// call in one process emitted every row twice. Copy it first: Fields is nil
	// in the template, so append allocates fresh per call.
	local := make([]block, len(blocks))
	copy(local, blocks)

	byKey := map[string]*block{}
	for i := range local {
		byKey[local[i].Key] = &local[i]
	}

	// Anything not claimed by a block lands on the top-level page, with its whole
	// subtree, so a new key in the Go model is documented rather than merely
	// named.
	top := &block{
		Key: "top-level", Title: "Top level", Order: 1, Status: statusShipped,
		Summary: "Required keys, project-wide scalars, and the single-workload shorthand.",
		ReadWhen: []string{
			"Starting a new project file",
			"Working out which keys are required",
		},
	}

	names := make([]string, 0, len(props))
	for name := range props {
		names = append(names, name)
	}
	sort.Strings(names)

	for _, name := range names {
		node, _ := props[name].(map[string]any)
		if node == nil {
			return nil, fmt.Errorf("top-level key %q is not an object in the schema", name)
		}
		target := byKey[name]
		if target == nil {
			// An unclaimed key gets its own row plus everything beneath it. Only
			// emitting the row would document `routes` as a bare list and lose
			// all seven of its item fields.
			merged := collapse(node)
			target = top
			target.Fields = append(target.Fields, field{
				Path:        name,
				Type:        typeOf(merged),
				Enum:        enumOf(merged),
				Default:     defaultOf(merged),
				Description: descriptionOf(merged),
				Required:    required[name],
			})
			nested, err := walk(merged, name, 0)
			if err != nil {
				return nil, fmt.Errorf("top-level key %q: %w", name, err)
			}
			target.Fields = append(target.Fields, nested...)
			continue
		}
		// A block page is the key's subtree. The key itself is required-ness
		// worth stating, and `environments` is mandatory, so record it.
		if required[name] {
			target.RequiredKey = true
		}
		fields, err := walk(node, "", 0)
		if err != nil {
			return nil, fmt.Errorf("block %q: %w", name, err)
		}
		target.Fields = append(target.Fields, fields...)
	}

	pages := map[string]string{}
	all := []*block{top}
	for i := range local {
		all = append(all, &local[i])
	}

	for _, b := range all {
		sort.SliceStable(b.Fields, func(i, j int) bool { return b.Fields[i].Path < b.Fields[j].Path })
		name := "fields/" + b.Key + ".mdx"
		pages[name] = renderBlockPage(b)
	}
	return pages, nil
}

// maxDepth bounds the recursion. The schema is a finite tree with no cycles, so
// this is a tripwire rather than a limit: exceeding it means the model grew a
// level, and the fields below it would otherwise vanish from the reference with
// nothing to say so.
const maxDepth = 12

// walk flattens a schema node into dotted field paths. It follows the three
// shapes this schema uses: object properties, an `additionalProperties` map
// keyed by a user-chosen name, and arrays of objects. The scalar shorthand forms
// appear as `oneOf` branches, which are merged rather than listed, since an
// author wants one row per field, not one row per accepted spelling.
//
// Every shape it cannot render is an error rather than an empty result. Silence
// here is indistinguishable from "this node genuinely has no fields", which is
// how a subtree disappears from a published reference without anyone noticing.
func walk(node map[string]any, prefix string, depth int) ([]field, error) {
	if depth > maxDepth {
		return nil, fmt.Errorf("%s is nested deeper than %d levels; raise maxDepth or the fields beneath it go undocumented", prefix, maxDepth)
	}
	node = collapse(node)

	if _, ok := node["patternProperties"]; ok && !onlyExtensionPatterns(node) {
		return nil, fmt.Errorf("%s uses patternProperties for something other than `x-` extensions, which this generator does not render", prefix)
	}

	if items, ok := node["items"].(map[string]any); ok {
		return walk(items, prefix+"[]", depth+1)
	}

	if props, ok := node["properties"].(map[string]any); ok {
		required := stringSet(node["required"])
		var out []field
		names := make([]string, 0, len(props))
		for name := range props {
			names = append(names, name)
		}
		sort.Strings(names)
		for _, name := range names {
			child, _ := props[name].(map[string]any)
			if child == nil {
				return nil, fmt.Errorf("%s.%s is not an object in the schema", prefix, name)
			}
			path := name
			if prefix != "" {
				path = prefix + "." + name
			}
			child = collapse(child)
			nested, err := walk(child, path, depth+1)
			if err != nil {
				return nil, err
			}
			out = append(out, field{
				Path:        path,
				Type:        typeOf(child),
				Enum:        enumOf(child),
				Default:     defaultOf(child),
				Description: descriptionOf(child),
				Required:    required[name],
			})
			out = append(out, nested...)
		}
		return out, nil
	}

	if extra, ok := node["additionalProperties"].(map[string]any); ok {
		next := prefix + ".<name>"
		if prefix == "" {
			next = "<name>"
		}
		return walk(extra, next, depth+1)
	}

	return nil, nil
}

// The schema uses patternProperties only to permit `x-` extension keys, which
// carry nothing and are documented in prose rather than per-field. Any other
// pattern is a shape this generator would silently drop.
func onlyExtensionPatterns(node map[string]any) bool {
	patterns, ok := node["patternProperties"].(map[string]any)
	if !ok {
		return true
	}
	for pattern := range patterns {
		if !strings.HasPrefix(pattern, "^x-") {
			return false
		}
	}
	return true
}

// collapse merges the branches of a oneOf/anyOf/allOf into one node. The scalar
// shorthands are why these exist — `image: nginx` and `image: {reference: nginx}`
// are the same field written two ways — and an author wants one row per field,
// not one row per accepted spelling.
//
// Two rules make the merge honest, and both were learned by getting them wrong.
//
// A branch that contributes nothing but `required` is stating an alternative,
// not a requirement. `oneOf` of `{required:[build]}`, `{required:[image]}`,
// `{required:[compose]}` says "exactly one of these", and merging it published
// the first branch as unconditional — the reference contradicting the loader in
// the column that matters most. A branch that also defines `properties`
// describes a shape, and the requirements it states for its own properties are
// real, so those are kept: that is what makes `env_files[].file` required inside
// the object form while `build` is not required at all.
//
// The branch carrying `properties` wins the scalar keys. Shorthand branches are
// declared first, so first-wins gave `image` the type `string` while listing its
// object sub-fields underneath it.
func collapse(node map[string]any) map[string]any {
	for _, key := range []string{"allOf", "oneOf", "anyOf"} {
		branches, ok := node[key].([]any)
		if !ok {
			continue
		}
		merged := map[string]any{}
		for k, v := range node {
			if k != key {
				merged[k] = v
			}
		}

		collapsed := make([]map[string]any, 0, len(branches))
		for _, raw := range branches {
			if branch, ok := raw.(map[string]any); ok {
				collapsed = append(collapsed, collapse(branch))
			}
		}

		// Richest first, so the object form supplies type and properties.
		sort.SliceStable(collapsed, func(i, j int) bool {
			return branchRank(collapsed[i]) > branchRank(collapsed[j])
		})

		exclusive := key != "allOf"
		for _, branch := range collapsed {
			statesOnlyRequirements := branch["properties"] == nil
			for k, v := range branch {
				if k == "required" && exclusive && statesOnlyRequirements {
					continue
				}
				if _, taken := merged[k]; !taken {
					merged[k] = v
				}
			}
		}
		return merged
	}
	return node
}

// branchRank orders combinator branches by how much they describe. A branch with
// properties describes a shape; one with only a type describes a spelling.
func branchRank(branch map[string]any) int {
	switch {
	case branch["properties"] != nil:
		return 3
	case branch["additionalProperties"] != nil, branch["items"] != nil:
		return 2
	case branch["type"] != nil:
		return 1
	default:
		return 0
	}
}

func typeOf(node map[string]any) string {
	node = collapse(node)
	if len(enumOf(node)) > 0 {
		return "enum"
	}
	switch t := node["type"].(type) {
	case string:
		if t == "array" {
			// A list whose items are a closed set is worth naming: the page
			// otherwise says "list" for a field where only two values load.
			if items, ok := collapse(node)["items"].(map[string]any); ok {
				if values := enumOf(collapse(items)); len(values) > 0 {
					quoted := make([]string, 0, len(values))
					for _, v := range values {
						quoted = append(quoted, "`"+v+"`")
					}
					return "list of " + strings.Join(quoted, " · ")
				}
			}
			return "list"
		}
		if t == "object" {
			if _, keyed := node["additionalProperties"].(map[string]any); keyed {
				return "map"
			}
			return "object"
		}
		return t
	case []any:
		var parts []string
		for _, v := range t {
			if s, ok := v.(string); ok && s != "null" {
				parts = append(parts, s)
			}
		}
		return strings.Join(parts, " · ")
	}
	if _, ok := node["properties"]; ok {
		return "object"
	}
	return ""
}

func enumOf(node map[string]any) []string {
	raw, ok := node["enum"].([]any)
	if !ok {
		return nil
	}
	var out []string
	for _, v := range raw {
		out = append(out, fmt.Sprint(v))
	}
	return out
}

func defaultOf(node map[string]any) string {
	v, ok := node["default"]
	if !ok {
		return ""
	}
	return fmt.Sprint(v)
}

func descriptionOf(node map[string]any) string {
	s, _ := node["description"].(string)
	return strings.TrimSpace(s)
}

func stringSet(raw any) map[string]bool {
	out := map[string]bool{}
	list, ok := raw.([]any)
	if !ok {
		return out
	}
	for _, v := range list {
		if s, ok := v.(string); ok {
			out[s] = true
		}
	}
	return out
}

func renderBlockPage(b *block) string {
	var buf bytes.Buffer

	fmt.Fprintln(&buf, "---")
	fmt.Fprintf(&buf, "title: %s\n", jsonString(b.Title))
	fmt.Fprintf(&buf, "description: %s\n", jsonString(b.Summary))
	fmt.Fprintf(&buf, "summary: %s\n", jsonString(b.Summary))
	fmt.Fprintf(&buf, "status: %s\n", b.Status)
	fmt.Fprintln(&buf, "generated: true")
	fmt.Fprintf(&buf, "sidebar:\n  order: %d\n", b.Order)
	if len(b.ReadWhen) > 0 {
		fmt.Fprintln(&buf, "read_when:")
		for _, when := range b.ReadWhen {
			fmt.Fprintf(&buf, "  - %s\n", jsonString(when))
		}
	}
	fmt.Fprintln(&buf, "---")
	fmt.Fprintln(&buf)
	fmt.Fprintln(&buf, generatedMarker)
	fmt.Fprintln(&buf)

	switch b.Status {
	case statusSchemaOnly:
		fmt.Fprintln(&buf, ":::caution[Accepted, not yet executable]")
		fmt.Fprintln(&buf, "The loader validates this block and it is published in the JSON Schema, so your")
		fmt.Fprintln(&buf, "editor will complete it. The behaviour behind it is an open proposal. Declaring")
		fmt.Fprintln(&buf, "it changes nothing on the target.")
		fmt.Fprintln(&buf, ":::")
		fmt.Fprintln(&buf)
	case statusIntentOnly:
		fmt.Fprintln(&buf, ":::note[Intent only]")
		fmt.Fprintln(&buf, "These values are validated and carried into plans, but the local engine runs no")
		fmt.Fprintln(&buf, "continuous collectors or alert managers. Status reports them as declared, not")
		fmt.Fprintln(&buf, "managed.")
		fmt.Fprintln(&buf, ":::")
		fmt.Fprintln(&buf)
	case statusShipped:
	}

	if b.RequiredKey {
		fmt.Fprintf(&buf, ":::caution[`%s` is required]\n", b.Key)
		fmt.Fprintf(&buf, "A project file that does not declare `%s` fails to load.\n", b.Key)
		fmt.Fprintln(&buf, ":::")
		fmt.Fprintln(&buf)
	}

	fmt.Fprintln(&buf, "This page is generated from the same Go declarations the loader enforces, so it")
	fmt.Fprintln(&buf, "cannot drift from what `ob validate` accepts.")
	fmt.Fprintln(&buf)

	if len(b.Fields) == 0 {
		fmt.Fprintln(&buf, "This block declares no fields.")
		return buf.String()
	}

	// Every row is a dotted path, so the bare field name is never a token on
	// its own. Site search then ranks a passing mention in a guide above the
	// reference page that actually defines the field — and for a name used
	// nowhere else, returns nothing at all. This index gives each leaf name one
	// clean occurrence, and doubles as a way to skim an eighty-row page.
	if names := leafNames(b.Fields); len(names) > 0 {
		fmt.Fprintln(&buf, "## Fields on this page")
		fmt.Fprintln(&buf)
		quoted := make([]string, 0, len(names))
		for _, name := range names {
			quoted = append(quoted, "`"+name+"`")
		}
		fmt.Fprintln(&buf, strings.Join(quoted, " · "))
		fmt.Fprintln(&buf)
		fmt.Fprintln(&buf, "## Reference")
		fmt.Fprintln(&buf)
	}

	fmt.Fprintln(&buf, "| Field | Type | Default | What it does |")
	fmt.Fprintln(&buf, "| --- | --- | --- | --- |")
	for _, f := range b.Fields {
		fmt.Fprintf(&buf, "| `%s`%s | %s | %s | %s |\n",
			f.Path,
			requiredMark(f.Required),
			typeCell(f),
			defaultCell(f),
			escapeCell(f.Description),
		)
	}
	// The legend only means something when a row carries the marker. Printing it
	// on a page with no required fields invites the reader to look for one.
	for _, f := range b.Fields {
		if f.Required {
			fmt.Fprintln(&buf)
			fmt.Fprintln(&buf, "`*` marks a field that is required within its own object.")
			break
		}
	}

	return buf.String()
}

// leafNames reduces the dotted paths to the distinct field names an author
// would actually search for, dropping the `<name>` map placeholder and the
// `[]` array marker that carry no meaning on their own.
func leafNames(fields []field) []string {
	seen := map[string]bool{}
	var out []string
	for _, f := range fields {
		parts := strings.Split(f.Path, ".")
		leaf := strings.TrimSuffix(parts[len(parts)-1], "[]")
		if leaf == "" || leaf == "<name>" || seen[leaf] {
			continue
		}
		seen[leaf] = true
		out = append(out, leaf)
	}
	sort.Strings(out)
	return out
}

func requiredMark(required bool) string {
	if required {
		return " `*`"
	}
	return ""
}

func typeCell(f field) string {
	if len(f.Enum) > 0 {
		quoted := make([]string, 0, len(f.Enum))
		for _, v := range f.Enum {
			quoted = append(quoted, "`"+v+"`")
		}
		return strings.Join(quoted, " · ")
	}
	if f.Type == "" {
		return "—"
	}
	return f.Type
}

func defaultCell(f field) string {
	if f.Default == "" {
		return "—"
	}
	return "`" + f.Default + "`"
}

func escapeCell(s string) string {
	s = strings.ReplaceAll(s, "|", "\\|")
	s = strings.Join(strings.Fields(s), " ")
	if s == "" {
		return "—"
	}
	return s
}

func jsonString(s string) string {
	b, _ := json.Marshal(s)
	return string(b)
}

