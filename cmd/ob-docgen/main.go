// renderCommand emits one command and everything beneath it. It recurses rather
// than unrolling a fixed number of levels: the previous two-level version could
// never describe `ob a b c`, and the only thing that would have noticed was a
// test in another package reporting it as stale documentation.
func renderCommand(buf *bytes.Buffer, obBin, name string, level int) error {
	body, err := help(obBin, strings.Fields(name)...)
	if err != nil {
		return err
	}

	fmt.Fprintf(buf, "%s ob %s\n\n", strings.Repeat("#", level), name)
	fmt.Fprintln(buf, "```")
	fmt.Fprintln(buf, strings.TrimRight(body, "\n"))
	fmt.Fprintln(buf, "```")
	fmt.Fprintln(buf)

	// A leaf command prints no command section, which is not a parse failure.
	nested, err := subcommands(body)
	if err != nil {
		return nil
	}
	for _, child := range nested {
		if err := renderCommand(buf, obBin, name+" "+child, level+1); err != nil {
			return err
		}
	}
	return nil
}

// help runs `ob <args> --help` and insists the answer is about the command that
// was asked for.
//
// Cobra answers an unknown command with the *root* help and exit 0, so a name
// misread out of a help listing would otherwise be published as a real command
// whose body is the root help. Tolerating a non-zero exit whenever anything
// reached stdout had the same shape: a truncated or half-written help became
// documentation.
func help(bin string, args ...string) (string, error) {
	cmd := exec.Command(bin, append(args, "--help")...)
	cmd.Env = append(os.Environ(), "NO_COLOR=1")
	var out, errOut bytes.Buffer
	cmd.Stdout = &out
	cmd.Stderr = &errOut
	if err := cmd.Run(); err != nil {
		return "", fmt.Errorf("`ob %s --help` failed: %w: %s", strings.Join(args, " "), err, strings.TrimSpace(errOut.String()))
	}
	if len(args) > 0 {
		want := "ob " + strings.Join(args, " ")
		if !strings.Contains(out.String(), want) {
			return "", fmt.Errorf("`%s --help` did not describe %q: the command does not exist, or cobra's help template changed", want, want)
		}
	}
	return out.String(), nil
}

// subcommands reads the command sections cobra prints. Parsing help output is
// coarse, but it is the only view of the command tree available from outside
// package main.
//
// A help text with no command section at all returns an error rather than an
// empty list. The two are indistinguishable to the caller otherwise, and the
// difference is "this is a leaf command" versus "cobra's template changed and
// the entire reference is about to be published empty". Blank lines do not end
// the scan, because command groups are separated by them.
func subcommands(helpText string) ([]string, error) {
	var out []string
	seen := map[string]bool{}
	sawSection := false
	inSection := false

	for _, line := range strings.Split(helpText, "\n") {
		trimmed := strings.TrimSpace(line)
		if strings.HasSuffix(trimmed, "Commands:") {
			sawSection, inSection = true, true
			continue
		}
		if !inSection {
			continue
		}
		if trimmed == "" {
			// Cobra separates command groups with a blank line; the section is
			// only over when unindented text arrives.
			continue
		}
		if !strings.HasPrefix(line, " ") {
			inSection = false
			continue
		}
		fields := strings.Fields(trimmed)
		if len(fields) == 0 {
			continue
		}
		name := fields[0]
		// Cobra generates these two; they are not ours to document.
		if name == "help" || name == "completion" || seen[name] {
			continue
		}
		seen[name] = true
		out = append(out, name)
	}

	if !sawSection {
		return nil, fmt.Errorf("no %q section found in the help text", "Commands:")
	}
	sort.Strings(out)
	return out, nil
}
