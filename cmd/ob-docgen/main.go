// Command ob-docgen writes the generated half of the documentation site.
//
// Three references in this product are already enumerated in Go, drift-tested,
// and published: the project-file schema, the loader's error codes, and the
// lifecycle failure contract. Writing them again by hand in Markdown would
// create a second source that can disagree with the first, and a published
// contract that disagrees with the loader is worse than none — it teaches the
// author something untrue and they learn to ignore it.
//
// So this program is the only writer of everything under
// `site/src/content/docs/reference/fields/`, `reference/errors`, and
// `reference/cli`. Those files carry a generated marker, and `--check` fails
// when what is on disk differs from what the current binary would produce.
// That turns "the documentation is current" into a build result rather than a
// claim.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"

	"github.com/labstack/onebox/internal/app"
	"github.com/labstack/onebox/internal/onebox"
)

// MDX parses HTML comments as JSX, so the marker uses the MDX comment form.
const generatedMarker = "{/* Generated by cmd/ob-docgen. Do not edit by hand. */}"

func main() {
	var (
		out    string
		public string
		obBin  string
		check  bool
	)
	flag.StringVar(&out, "out", "site/src/content/docs/reference", "directory to write generated reference pages into")
	flag.StringVar(&public, "public", "site/public", "directory to publish machine-readable artifacts into")
	flag.StringVar(&obBin, "ob", "", "path to a built ob binary, for the CLI reference (default: look on PATH)")
	flag.BoolVar(&check, "check", false, "fail if the files on disk differ from what would be generated")
	flag.Parse()

	files, err := generate(obBin)
	if err != nil {
		fmt.Fprintln(os.Stderr, "ob-docgen:", err)
		os.Exit(1)
	}

	// The site publishes the schema it documents. Copying the checked-in file
	// would create a third copy that can disagree with the loader, so it is
	// produced from the same call `ob schema` makes.
	schema, err := app.JSONSchema()
	if err != nil {
		fmt.Fprintln(os.Stderr, "ob-docgen:", err)
		os.Exit(1)
	}
	schema = append(schema, '\n')
	publicFiles := map[string]string{"onebox.run-v1.schema.json": string(schema)}

	if check {
		if err := verify(out, files); err != nil {
			fmt.Fprintln(os.Stderr, "ob-docgen:", err)
			os.Exit(1)
		}
		if err := verify(public, publicFiles); err != nil {
			fmt.Fprintln(os.Stderr, "ob-docgen:", err)
			os.Exit(1)
		}
		fmt.Printf("ob-docgen: %d generated page(s) and %d published artifact(s) are current\n", len(files), len(publicFiles))
		return
	}

	for name, body := range publicFiles {
		path := filepath.Join(public, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			fmt.Fprintln(os.Stderr, "ob-docgen:", err)
			os.Exit(1)
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			fmt.Fprintln(os.Stderr, "ob-docgen:", err)
			os.Exit(1)
		}
	}

	for name, body := range files {
		path := filepath.Join(out, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			fmt.Fprintln(os.Stderr, "ob-docgen:", err)
			os.Exit(1)
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			fmt.Fprintln(os.Stderr, "ob-docgen:", err)
			os.Exit(1)
		}
	}
	fmt.Printf("ob-docgen: wrote %d page(s) to %s\n", len(files), out)
}

func verify(out string, want map[string]string) error {
	var stale []string
	for name, body := range want {
		got, err := os.ReadFile(filepath.Join(out, name))
		if err != nil {
			stale = append(stale, name+" (missing)")
			continue
		}
		if string(got) != body {
			stale = append(stale, name)
		}
	}
	if len(stale) > 0 {
		sort.Strings(stale)
		return fmt.Errorf("generated documentation is stale — run `just docs-generate`:\n  %s", strings.Join(stale, "\n  "))
	}
	return nil
}

func generate(obBin string) (map[string]string, error) {
	files := map[string]string{}

	schema, err := loadSchema()
	if err != nil {
		return nil, err
	}
	fieldPages, err := renderFieldPages(schema)
	if err != nil {
		return nil, err
	}
	for name, body := range fieldPages {
		files[name] = body
	}

	files["errors.mdx"] = renderErrorPage()

	cli, err := renderCLIPage(obBin)
	if err != nil {
		return nil, err
	}
	if cli != "" {
		files["cli.mdx"] = cli
	}

	return files, nil
}

