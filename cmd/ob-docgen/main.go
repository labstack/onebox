func renderFieldPages(schema map[string]any) (map[string]string, error) {
	props, _ := schema["properties"].(map[string]any)
	if props == nil {
		return nil, fmt.Errorf("the JSON Schema has no top-level properties")
	}
	required := stringSet(schema["required"])

	byKey := map[string]*block{}
	for i := range blocks {
		byKey[blocks[i].Key] = &blocks[i]
	}

	// Anything not claimed by a block lands on the top-level page. A new field
	// in the Go model therefore appears in the documentation without anyone
	// remembering to add it.
	top := &block{
		Key: "top-level", Title: "Top level", Order: 1, Status: "shipped",
		Summary: "Required keys, project-wide scalars, and the single-workload shorthand.",
		ReadWhen: []string{
			"Starting a new project file",
			"Working out which keys are required",
		},
	}

	for name, raw := range props {
		node, _ := raw.(map[string]any)
		if node == nil {
			continue
		}
		target := byKey[name]
		if target == nil {
			target = top
			target.Fields = append(target.Fields, field{
				Path:        name,
				Type:        typeOf(node),
				Enum:        enumOf(node),
				Default:     defaultOf(node),
				Description: descriptionOf(node),
				Required:    required[name],
			})
			continue
		}
		target.Fields = append(target.Fields, walk(node, "", 0)...)
	}

	pages := map[string]string{}
	all := append([]*block{top}, func() []*block {
		var out []*block
		for i := range blocks {
			out = append(out, &blocks[i])
		}
		return out
	}()...)

	for _, b := range all {
		sort.SliceStable(b.Fields, func(i, j int) bool { return b.Fields[i].Path < b.Fields[j].Path })
		name := "fields/" + b.Key + ".mdx"
		pages[name] = renderBlockPage(b)
	}
	return pages, nil
}

// walk flattens a schema node into dotted field paths. It follows the three
// shapes this schema actually uses: object properties, an `additionalProperties`
// map keyed by a user-chosen name, and arrays of objects. The scalar shorthand
// forms appear as `oneOf` branches, which are merged rather than listed, since
// an author wants one row per field, not one row per accepted spelling.
func walk(node map[string]any, prefix string, depth int) []field {
	if depth > 4 {
		return nil
	}
	node = collapse(node)

	if items, ok := node["items"].(map[string]any); ok {
		return walk(items, prefix+"[]", depth)
	}

	if props, ok := node["properties"].(map[string]any); ok {
		required := stringSet(node["required"])
		var out []field
		names := make([]string, 0, len(props))
		for name := range props {
			names = append(names, name)
		}
		sort.Strings(names)
		for _, name := range names {
			child, _ := props[name].(map[string]any)
			if child == nil {
				continue
			}
			path := name
			if prefix != "" {
				path = prefix + "." + name
			}
			child = collapse(child)
			nested := walk(child, path, depth+1)
			out = append(out, field{
				Path:        path,
				Type:        typeOf(child),
				Enum:        enumOf(child),
				Default:     defaultOf(child),
				Description: descriptionOf(child),
				Required:    required[name],
			})
			out = append(out, nested...)
		}
		return out
	}

	if extra, ok := node["additionalProperties"].(map[string]any); ok {
		next := prefix + ".<name>"
		if prefix == "" {
			next = "<name>"
		}
		return walk(extra, next, depth)
	}

	return nil
}

// collapse merges the branches of a oneOf/anyOf/allOf into one node. The scalar
// shorthands are the reason these exist — `image: nginx` and
// `image: {reference: nginx}` are the same field written two ways — so the
// richest branch is what an author needs to see.
func collapse(node map[string]any) map[string]any {
	for _, key := range []string{"allOf", "oneOf", "anyOf"} {
		branches, ok := node[key].([]any)
		if !ok {
			continue
		}
		merged := map[string]any{}
		for k, v := range node {
			if k == key {
				continue
			}
			merged[k] = v
		}
		for _, raw := range branches {
			branch, ok := raw.(map[string]any)
			if !ok {
				continue
			}
			branch = collapse(branch)
			for k, v := range branch {
				if _, taken := merged[k]; !taken {
					merged[k] = v
				}
			}
		}
		return merged
	}
	return node
}

func typeOf(node map[string]any) string {
	node = collapse(node)
	if len(enumOf(node)) > 0 {
		return "enum"
	}
	switch t := node["type"].(type) {
	case string:
		if t == "array" {
			return "list"
		}
		if t == "object" {
			if _, keyed := node["additionalProperties"].(map[string]any); keyed {
				return "map"
			}
			return "object"
		}
		return t
	case []any:
		var parts []string
		for _, v := range t {
			if s, ok := v.(string); ok && s != "null" {
				parts = append(parts, s)
			}
		}
		return strings.Join(parts, " · ")
	}
	if _, ok := node["properties"]; ok {
		return "object"
	}
	return ""
}

func enumOf(node map[string]any) []string {
	raw, ok := node["enum"].([]any)
	if !ok {
		return nil
	}
	var out []string
	for _, v := range raw {
		out = append(out, fmt.Sprint(v))
	}
	return out
}

func defaultOf(node map[string]any) string {
	v, ok := node["default"]
	if !ok {
		return ""
	}
	return fmt.Sprint(v)
}

func descriptionOf(node map[string]any) string {
	s, _ := node["description"].(string)
	return strings.TrimSpace(s)
}

func stringSet(raw any) map[string]bool {
	out := map[string]bool{}
	list, ok := raw.([]any)
	if !ok {
		return out
	}
	for _, v := range list {
		if s, ok := v.(string); ok {
			out[s] = true
		}
	}
	return out
}

func renderBlockPage(b *block) string {
	var buf bytes.Buffer

	fmt.Fprintln(&buf, "---")
	fmt.Fprintf(&buf, "title: %s\n", jsonString(b.Title))
	fmt.Fprintf(&buf, "description: %s\n", jsonString(b.Summary))
	fmt.Fprintf(&buf, "summary: %s\n", jsonString(b.Summary))
	fmt.Fprintf(&buf, "status: %s\n", b.Status)
	fmt.Fprintln(&buf, "generated: true")
	fmt.Fprintf(&buf, "sidebar:\n  order: %d\n", b.Order)
	if len(b.ReadWhen) > 0 {
		fmt.Fprintln(&buf, "read_when:")
		for _, when := range b.ReadWhen {
			fmt.Fprintf(&buf, "  - %s\n", jsonString(when))
		}
	}
	fmt.Fprintln(&buf, "---")
	fmt.Fprintln(&buf)
	fmt.Fprintln(&buf, generatedMarker)
	fmt.Fprintln(&buf)

	switch b.Status {
	case "schema-only":
		fmt.Fprintln(&buf, ":::caution[Accepted, not yet executable]")
		fmt.Fprintln(&buf, "The loader validates this block and it is published in the JSON Schema, so your")
		fmt.Fprintln(&buf, "editor will complete it. The behaviour behind it is an open proposal. Declaring")
		fmt.Fprintln(&buf, "it changes nothing on the target.")
		fmt.Fprintln(&buf, ":::")
		fmt.Fprintln(&buf)
	case "intent-only":
		fmt.Fprintln(&buf, ":::note[Intent only]")
		fmt.Fprintln(&buf, "These values are validated and carried into plans, but the local engine runs no")
		fmt.Fprintln(&buf, "continuous collectors or alert managers. Status reports them as declared, not")
		fmt.Fprintln(&buf, "managed.")
		fmt.Fprintln(&buf, ":::")
		fmt.Fprintln(&buf)
	}

	fmt.Fprintln(&buf, "This page is generated from the same Go declarations the loader enforces, so it")
	fmt.Fprintln(&buf, "cannot drift from what `ob validate` accepts.")
	fmt.Fprintln(&buf)

	if len(b.Fields) == 0 {
		fmt.Fprintln(&buf, "This block declares no fields.")
		return buf.String()
	}

	// Every row is a dotted path, so the bare field name is never a token on
	// its own. Site search then ranks a passing mention in a guide above the
	// reference page that actually defines the field — and for a name used
	// nowhere else, returns nothing at all. This index gives each leaf name one
	// clean occurrence, and doubles as a way to skim an eighty-row page.
	if names := leafNames(b.Fields); len(names) > 0 {
		fmt.Fprintln(&buf, "## Fields on this page")
		fmt.Fprintln(&buf)
		quoted := make([]string, 0, len(names))
		for _, name := range names {
			quoted = append(quoted, "`"+name+"`")
		}
		fmt.Fprintln(&buf, strings.Join(quoted, " · "))
		fmt.Fprintln(&buf)
		fmt.Fprintln(&buf, "## Reference")
		fmt.Fprintln(&buf)
	}

	fmt.Fprintln(&buf, "| Field | Type | Default | What it does |")
	fmt.Fprintln(&buf, "| --- | --- | --- | --- |")
	for _, f := range b.Fields {
		fmt.Fprintf(&buf, "| `%s`%s | %s | %s | %s |\n",
			f.Path,
			requiredMark(f.Required),
			typeCell(f),
			defaultCell(f),
			escapeCell(f.Description),
		)
	}
	fmt.Fprintln(&buf)
	fmt.Fprintln(&buf, "`*` marks a required field.")

	return buf.String()
}

// leafNames reduces the dotted paths to the distinct field names an author
// would actually search for, dropping the `<name>` map placeholder and the
// `[]` array marker that carry no meaning on their own.
func leafNames(fields []field) []string {
	seen := map[string]bool{}
	var out []string
	for _, f := range fields {
		parts := strings.Split(f.Path, ".")
		leaf := strings.TrimSuffix(parts[len(parts)-1], "[]")
		if leaf == "" || leaf == "<name>" || seen[leaf] {
			continue
		}
		seen[leaf] = true
		out = append(out, leaf)
	}
	sort.Strings(out)
	return out
}

func requiredMark(required bool) string {
	if required {
		return " `*`"
	}
	return ""
}

func typeCell(f field) string {
	if len(f.Enum) > 0 {
		quoted := make([]string, 0, len(f.Enum))
		for _, v := range f.Enum {
			quoted = append(quoted, "`"+v+"`")
		}
		return strings.Join(quoted, " · ")
	}
	if f.Type == "" {
		return "—"
	}
	return f.Type
}

func defaultCell(f field) string {
	if f.Default == "" {
		return "—"
	}
	return "`" + f.Default + "`"
}

func escapeCell(s string) string {
	s = strings.ReplaceAll(s, "|", "\\|")
	s = strings.Join(strings.Fields(s), " ")
	if s == "" {
		return "—"
	}
	return s
}

func jsonString(s string) string {
	b, _ := json.Marshal(s)
	return string(b)
}

