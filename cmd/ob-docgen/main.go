// Command ob-docgen writes the generated half of the documentation site.
//
// Three references in this product are already enumerated in Go, drift-tested,
// and published: the project-file schema, the loader's error codes, and the
// lifecycle failure contract. Writing them again by hand in Markdown would
// create a second source that can disagree with the first, and a published
// contract that disagrees with the loader is worse than none — it teaches the
// author something untrue and they learn to ignore it.
//
// So this program is the only writer of `site/src/content/docs/reference/`
// — the field pages, `errors.mdx` and `cli.mdx` — and of the schema published at
// `site/public/onebox.run-v1.schema.json`. Those pages carry a generated marker,
// which `--check` reads in both directions: it fails when a page differs from
// what this binary would produce, and when a marked page survives that no
// generator produces any more.
//
// `TestCommittedPagesMatchTheGenerator` runs the same comparison under
// `go test ./...`, so currency does not depend on anyone remembering a recipe.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"

	"github.com/labstack/onebox/internal/app"
	"github.com/labstack/onebox/internal/onebox"
)

// MDX parses HTML comments as JSX, so the marker uses the MDX comment form.
const generatedMarker = "{/* Generated by cmd/ob-docgen. Do not edit by hand. */}"

func main() {
	var (
		out    string
		public string
		obBin  string
		check  bool
	)
	flag.StringVar(&out, "out", "site/src/content/docs/reference", "directory to write generated reference pages into")
	flag.StringVar(&public, "public", "site/public", "directory to publish machine-readable artifacts into")
	flag.StringVar(&obBin, "ob", "", "path to a built ob binary, for the CLI reference (default: look on PATH)")
	flag.BoolVar(&check, "check", false, "fail if the files on disk differ from what would be generated")
	flag.Parse()

	files, err := generate(obBin)
	if err != nil {
		fmt.Fprintln(os.Stderr, "ob-docgen:", err)
		os.Exit(1)
	}

	// The site publishes the schema it documents. Copying the checked-in file
	// would give the published artifact a second derivation path, one that can
	// lag the loader without the loader changing. Producing it from
	// app.JSONSchema() — the same call `ob schema` makes — keeps one.
	schema, err := app.JSONSchema()
	if err != nil {
		fmt.Fprintln(os.Stderr, "ob-docgen:", err)
		os.Exit(1)
	}
	schema = append(schema, '\n')
	publicFiles := map[string]string{"onebox.run-v1.schema.json": string(schema)}

	if check {
		if err := verify(out, files); err != nil {
			fmt.Fprintln(os.Stderr, "ob-docgen:", err)
			os.Exit(1)
		}
		if err := verify(public, publicFiles); err != nil {
			fmt.Fprintln(os.Stderr, "ob-docgen:", err)
			os.Exit(1)
		}
		fmt.Printf("ob-docgen: %d generated page(s) and %d published artifact(s) are current\n", len(files), len(publicFiles))
		return
	}

	for name, body := range publicFiles {
		path := filepath.Join(public, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			fmt.Fprintln(os.Stderr, "ob-docgen:", err)
			os.Exit(1)
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			fmt.Fprintln(os.Stderr, "ob-docgen:", err)
			os.Exit(1)
		}
	}

	for name, body := range files {
		path := filepath.Join(out, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			fmt.Fprintln(os.Stderr, "ob-docgen:", err)
			os.Exit(1)
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			fmt.Fprintln(os.Stderr, "ob-docgen:", err)
			os.Exit(1)
		}
	}
	fmt.Printf("ob-docgen: wrote %d page(s) to %s\n", len(files), out)
}

// verify compares what is on disk with what the binary would write — in both
// directions.
//
// Comparing only the files the generator would produce leaves the opposite
// failure invisible: rename a key in the registry and the old page stays
// committed, keeps its autogenerated sidebar entry, and is advertised to agents
// as shipped, while the check reports everything current. A published page for a
// block the loader no longer accepts is worse than a missing one, so the marker
// that identifies generated files is read here rather than merely written.
func verify(out string, want map[string]string) error {
	var stale []string
	for name, body := range want {
		got, err := os.ReadFile(filepath.Join(out, name))
		if err != nil {
			stale = append(stale, name+" (missing)")
			continue
		}
		if string(got) != body {
			stale = append(stale, name)
		}
	}

	orphans, err := orphanedPages(out, want)
	if err != nil {
		return err
	}
	stale = append(stale, orphans...)

	if len(stale) > 0 {
		sort.Strings(stale)
		return fmt.Errorf("generated documentation is stale — run `just docs-generate`:\n  %s", strings.Join(stale, "\n  "))
	}
	return nil
}

func orphanedPages(out string, want map[string]string) ([]string, error) {
	var orphans []string
	err := filepath.WalkDir(out, func(path string, entry os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() || filepath.Ext(path) != ".mdx" {
			return nil
		}
		rel, err := filepath.Rel(out, path)
		if err != nil {
			return err
		}
		if _, expected := want[filepath.ToSlash(rel)]; expected {
			return nil
		}
		body, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if bytes.Contains(body, []byte(generatedMarker)) {
			orphans = append(orphans, filepath.ToSlash(rel)+" (orphaned: no generator produces this page — delete it)")
		}
		return nil
	})
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, fmt.Errorf("cannot enumerate %s: %w", out, err)
	}
	return orphans, nil
}

func generate(obBin string) (map[string]string, error) {
	files := map[string]string{}

	schema, err := loadSchema()
	if err != nil {
		return nil, err
	}
	fieldPages, err := renderFieldPages(schema)
	if err != nil {
		return nil, err
	}
	for name, body := range fieldPages {
		files[name] = body
	}

	files["errors.mdx"] = renderErrorPage()

	cli, err := renderCLIPage(obBin)
	if err != nil {
		return nil, err
	}
	if cli != "" {
		files["cli.mdx"] = cli
	}

	return files, nil
}

// ---------------------------------------------------------------- schema ---

func loadSchema() (map[string]any, error) {
	body, err := app.JSONSchema()
	if err != nil {
		return nil, fmt.Errorf("cannot produce the JSON Schema: %w", err)
	}
	var schema map[string]any
	if err := json.Unmarshal(body, &schema); err != nil {
		return nil, fmt.Errorf("cannot decode the JSON Schema: %w", err)
	}
	return schema, nil
}

// field is one row of a reference table: a dotted path, its type, its default
// and its description, flattened out of the schema's nesting.
type field struct {
	Path        string
	Type        string
	Enum        []string
	Default     string
	Description string
	Required    bool
}

// block is one generated page: a top-level key and every field beneath it.
type block struct {
	Key      string
	Title    string
	Summary  string
	Status   status
	ReadWhen []string
	Order    int
	Fields   []field

	// RequiredKey records that the project file must declare this key at all.
	// It is read from the schema rather than authored, because a page about a
	// mandatory block that never says so is the reference failing at its
	// first job.
	RequiredKey bool
}

// status is the honesty marker a page carries. The vocabulary is closed here so
// the registry cannot invent a fourth value that the site's content schema would
// then reject at build time.
